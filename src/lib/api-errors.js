const ERROR_CODES = new Set(['VALIDATION_FAILED', 'INVALID_ARGUMENT', 'AUTH_REQUIRED', 'PROXY_START_FAILED', 'PROXY_STOP_FAILED', 'OPERATION_IN_PROGRESS', 'SHUTTING_DOWN', 'INTERNAL_ERROR', 'RUNTIME_UNAVAILABLE', 'API_UNAVAILABLE', 'SECURE_STORAGE_UNAVAILABLE', 'SETTINGS_WRITE_FAILED', 'SSH_CONFIG_INVALID']);
for (const code of ['SSH_CONFIG_CHANGED', 'SSH_ALIAS_CONFLICT']) ERROR_CODES.add(code);
for (const code of ['PROFILE_CHANGED', 'DRAFT_CHANGED', 'OPERATION_CANCELLED', 'LOGIN_RESET_FAILED', 'AUTH_PERSIST_FAILED']) ERROR_CODES.add(code);
for (const code of ['SSH_KEY_INVALID', 'KEY_BACKUP_INVALID', 'KEY_TRANSACTION_FAILED', 'KEY_ROLLBACK_FAILED']) ERROR_CODES.add(code);
for (const code of ['SETTINGS_LOCKED', 'SETTINGS_DURABILITY_UNCERTAIN', 'SETTINGS_COMMIT_UNKNOWN', 'SETTINGS_RECOVERY_REQUIRED', 'SETTINGS_INVALID', 'SETTINGS_VERSION_UNSUPPORTED', 'SETTINGS_FILE_TOO_LARGE', 'SETTINGS_MIGRATION_FAILED', 'SETTINGS_LOAD_FAILED', 'SETTINGS_SAVE_FAILED', 'PROFILE_LIMIT', 'PROFILE_NOT_FOUND', 'PROFILE_LAST', 'PROFILE_ALIAS_CONFLICT', 'PROFILE_NAME_INVALID', 'SSH_KEY_MISSING', 'SSH_KEY_FINGERPRINT_MISMATCH']) ERROR_CODES.add(code);
for (const code of ['HISTORY_STORAGE_FAILED', 'HISTORY_WRITE_FAILED', 'HISTORY_INVALID', 'HISTORY_LOAD_FAILED']) ERROR_CODES.add(code);
ERROR_CODES.add('EXPORT_FAILED');
for (const code of ['AUTOSTART_UNAVAILABLE', 'AUTOSTART_CONFLICT', 'AUTOSTART_FAILED', 'NETWORK_UNAVAILABLE', 'WSS_FAILED', 'TLS_FAILED', 'TIMEOUT', 'PORT_IN_USE']) ERROR_CODES.add(code);
ERROR_CODES.add('RECOVERY_EXHAUSTED');
ERROR_CODES.add('ONBOARDING_NOT_READY');
ERROR_CODES.add('SSH_KEY_PERMISSIONS');
for (const code of ['UPDATE_NETWORK', 'UPDATE_NO_RELEASE', 'UPDATE_INVALID_METADATA', 'UPDATE_VERSION_REJECTED',
  'UPDATE_CHECKSUM_MISMATCH', 'UPDATE_SIGNATURE_INVALID', 'UPDATE_PERMISSION_DENIED', 'UPDATE_PREPARATION_FAILED',
  'UPDATE_INSTALL_FAILED', 'UPDATE_RESTART_REQUIRED', 'UPDATE_MANUAL_ONLY', 'AUTOSTART_UPDATE_FAILED']) ERROR_CODES.add(code);
const VALIDATION_CODES = new Set(['required', 'invalid_host', 'invalid_token', 'integer_range', 'invalid_boolean', 'invalid_enum', 'unknown_key']);

export function formatValidationError(code, t) {
  return VALIDATION_CODES.has(code) ? t(`validation_${code}`) : t('unknownError');
}

export function formatApiError(error, t) {
  return ERROR_CODES.has(error?.code) ? t(`error_${error.code}`) : t('unknownError');
}
